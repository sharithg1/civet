//! Secret session key and certificate fingerprint.
//!
//! Both are 32-byte values. In postcard they are encoded as raw bytes; in
//! human-readable formats (the JSON bootstrap line, the desktop UI) they are
//! lowercase hex strings.

use std::fmt;
use std::str::FromStr;

use serde::{Deserialize, Deserializer, Serialize, Serializer};
use subtle::ConstantTimeEq;

use crate::error::ProtoError;

/// Serde helpers shared by the fixed-size byte newtypes in this crate:
/// hex string when human-readable, raw byte array otherwise.
pub(crate) mod hex_array {
    use std::fmt;

    use serde::de::{Error as _, SeqAccess, Visitor};
    use serde::ser::SerializeTuple;
    use serde::{Deserialize, Deserializer, Serializer};

    pub fn serialize<S: Serializer, const N: usize>(
        bytes: &[u8; N],
        s: S,
    ) -> Result<S::Ok, S::Error> {
        if s.is_human_readable() {
            s.serialize_str(&hex::encode(bytes))
        } else {
            // Fixed-size tuple: postcard writes exactly N raw bytes.
            let mut t = s.serialize_tuple(N)?;
            for b in bytes {
                t.serialize_element(b)?;
            }
            t.end()
        }
    }

    struct ArrayVisitor<const N: usize>;

    impl<'de, const N: usize> Visitor<'de> for ArrayVisitor<N> {
        type Value = [u8; N];

        fn expecting(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
            write!(f, "{N} bytes")
        }

        fn visit_seq<A: SeqAccess<'de>>(self, mut seq: A) -> Result<[u8; N], A::Error> {
            let mut out = [0u8; N];
            for (i, slot) in out.iter_mut().enumerate() {
                *slot = seq
                    .next_element()?
                    .ok_or_else(|| A::Error::invalid_length(i, &self))?;
            }
            Ok(out)
        }
    }

    pub fn deserialize<'de, D: Deserializer<'de>, const N: usize>(
        d: D,
    ) -> Result<[u8; N], D::Error> {
        if d.is_human_readable() {
            let s = String::deserialize(d)?;
            let mut out = [0u8; N];
            hex::decode_to_slice(s.trim(), &mut out).map_err(D::Error::custom)?;
            Ok(out)
        } else {
            d.deserialize_tuple(N, ArrayVisitor::<N>)
        }
    }
}

pub(crate) fn parse_hex<const N: usize>(s: &str) -> Result<[u8; N], ProtoError> {
    let mut out = [0u8; N];
    hex::decode_to_slice(s.trim(), &mut out).map_err(|e| ProtoError::InvalidHex(e.to_string()))?;
    Ok(out)
}

/// Fill `buf` from the OS CSPRNG.
pub(crate) fn random_bytes(buf: &mut [u8]) -> Result<(), ProtoError> {
    getrandom::fill(buf).map_err(|e| ProtoError::Random(e.to_string()))
}

/// 256-bit secret generated by the daemon at startup and handed to the
/// client over SSH (in [`crate::BootstrapInfo`]). The client presents it in
/// [`crate::ClientHello`] over the certificate-pinned QUIC connection.
///
/// `Debug` is redacted; compare with [`SessionKey::ct_eq`] (constant time).
#[derive(Clone, PartialEq, Eq, Hash)]
pub struct SessionKey(pub [u8; 32]);

impl SessionKey {
    /// Length in bytes.
    pub const LEN: usize = 32;

    /// Generate a fresh random key from the OS CSPRNG.
    pub fn generate() -> Result<Self, ProtoError> {
        let mut k = [0u8; 32];
        random_bytes(&mut k)?;
        Ok(Self(k))
    }

    /// Raw key bytes.
    pub fn as_bytes(&self) -> &[u8; 32] {
        &self.0
    }

    /// Lowercase hex encoding (64 chars).
    pub fn to_hex(&self) -> String {
        hex::encode(self.0)
    }

    /// Parse from a 64-char hex string.
    pub fn from_hex(s: &str) -> Result<Self, ProtoError> {
        parse_hex(s).map(Self)
    }

    /// Constant-time equality, for authenticating a hello.
    pub fn ct_eq(&self, other: &SessionKey) -> bool {
        self.0.ct_eq(&other.0).into()
    }
}

impl fmt::Debug for SessionKey {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("SessionKey(<redacted>)")
    }
}

impl FromStr for SessionKey {
    type Err = ProtoError;
    fn from_str(s: &str) -> Result<Self, Self::Err> {
        Self::from_hex(s)
    }
}

impl Serialize for SessionKey {
    fn serialize<S: Serializer>(&self, s: S) -> Result<S::Ok, S::Error> {
        hex_array::serialize(&self.0, s)
    }
}

impl<'de> Deserialize<'de> for SessionKey {
    fn deserialize<D: Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
        hex_array::deserialize(d).map(Self)
    }
}

/// SHA-256 of the DER encoding of the daemon's self-signed TLS certificate.
/// The client pins the QUIC connection to exactly this certificate.
/// (Computed by `civet-transport`; this crate only carries it.)
#[derive(Clone, Copy, PartialEq, Eq, Hash)]
pub struct CertFingerprint(pub [u8; 32]);

impl CertFingerprint {
    /// Raw digest bytes.
    pub fn as_bytes(&self) -> &[u8; 32] {
        &self.0
    }

    /// Lowercase hex encoding (64 chars).
    pub fn to_hex(&self) -> String {
        hex::encode(self.0)
    }

    /// Parse from hex. Colons (`ab:cd:...`, as printed by openssl) are accepted.
    pub fn from_hex(s: &str) -> Result<Self, ProtoError> {
        let cleaned: String = s.chars().filter(|c| *c != ':').collect();
        parse_hex(&cleaned).map(Self)
    }
}

impl fmt::Debug for CertFingerprint {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "CertFingerprint({})", self.to_hex())
    }
}

impl fmt::Display for CertFingerprint {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.to_hex())
    }
}

impl FromStr for CertFingerprint {
    type Err = ProtoError;
    fn from_str(s: &str) -> Result<Self, Self::Err> {
        Self::from_hex(s)
    }
}

impl Serialize for CertFingerprint {
    fn serialize<S: Serializer>(&self, s: S) -> Result<S::Ok, S::Error> {
        hex_array::serialize(&self.0, s)
    }
}

impl<'de> Deserialize<'de> for CertFingerprint {
    fn deserialize<D: Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
        hex_array::deserialize(d).map(Self)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn session_key_hex_roundtrip_and_ct_eq() {
        let k = SessionKey::generate().unwrap();
        let parsed: SessionKey = k.to_hex().parse().unwrap();
        assert!(k.ct_eq(&parsed));
        assert!(!k.ct_eq(&SessionKey([0; 32])));
        assert_eq!(format!("{k:?}"), "SessionKey(<redacted>)");
    }

    #[test]
    fn generated_keys_differ() {
        let a = SessionKey::generate().unwrap();
        let b = SessionKey::generate().unwrap();
        assert_ne!(a, b);
    }

    #[test]
    fn bad_hex_is_rejected() {
        assert!(SessionKey::from_hex("zz").is_err());
        assert!(SessionKey::from_hex(&"ab".repeat(31)).is_err());
    }

    #[test]
    fn fingerprint_accepts_colons() {
        let fp = CertFingerprint([0xab; 32]);
        let colon = vec!["ab"; 32].join(":");
        assert_eq!(CertFingerprint::from_hex(&colon).unwrap(), fp);
        assert_eq!(fp.to_string(), "ab".repeat(32));
    }

    #[test]
    fn json_is_hex_postcard_is_raw() {
        let k = SessionKey([7; 32]);
        let json = serde_json::to_string(&k).unwrap();
        assert_eq!(json, format!("\"{}\"", "07".repeat(32)));
        assert_eq!(serde_json::from_str::<SessionKey>(&json).unwrap(), k);

        let bin = postcard::to_stdvec(&k).unwrap();
        assert_eq!(bin.len(), 32);
        assert_eq!(postcard::from_bytes::<SessionKey>(&bin).unwrap(), k);
    }
}
