    /// Fake `claude`/`codex` later on PATH: the shims find them (skipping
    /// the shim dir) and add the hook arguments exactly once.
    #[test]
    fn shims_find_real_program_and_inject() {
        use std::os::unix::fs::PermissionsExt;
        let dir = tempfile::tempdir().unwrap();
        let files = install(&dir.path().join("state")).unwrap();
        let real = dir.path().join("realbin");
        std::fs::create_dir_all(&real).unwrap();
        for name in ["claude", "codex"] {
            let p = real.join(name);
            std::fs::write(
                &p,
                "#!/bin/sh\nfor a in \"$@\"; do printf '[%s]' \"$a\"; done\n",
            )
            .unwrap();
            std::fs::set_permissions(&p, std::fs::Permissions::from_mode(0o755)).unwrap();
        }
        let home = dir.path().join("home");
        std::fs::create_dir_all(&home).unwrap();
        let path = format!(
            "{}:{}:/usr/bin:/bin",
            files.shim_dir.display(),
            real.display()
        );
        let run = |cmd: &str, status_file: bool| {
            let mut c = Command::new("/bin/sh");
            c.arg("-c")
                .arg(cmd)
                .env("PATH", &path)
                .env("HOME", &home)
                .env_remove("CODEX_HOME");
            if status_file {
                c.env(civet_proto::ENV_STATUS_FILE, dir.path().join("s"));
            } else {
                c.env_remove(civet_proto::ENV_STATUS_FILE);
            }
            let out = c.output().unwrap();
            assert!(out.status.success(), "{cmd}: {:?}", out);
            String::from_utf8(out.stdout).unwrap()
        };
        let settings = files.claude_settings.display().to_string();
        assert_eq!(
            run("claude -p hi", true),
            format!("[--settings][{settings}][-p][hi]")
        );
        assert_eq!(
            run("cd / && FOO=1 claude --settings x", true),
            "[--settings][x]"
        );
        assert_eq!(
            run("env A=1 claude", true),
            format!("[--settings][{settings}]")
        );
        // Outside a Civet pane: untouched.
        assert_eq!(run("claude a", false), "[a]");
        let out = run("codex exec hi", true);
        assert!(out.starts_with("[-c][notify=[\""), "{out}");
        assert!(
            out.contains("\"done\",\"--codex-notify\"]][exec][hi]"),
            "{out}"
        );
        assert_eq!(run("codex -c notify=[] x", true), "[-c][notify=[]][x]");
        // The user's own notify setting wins.
        std::fs::create_dir_all(home.join(".codex")).unwrap();
        std::fs::write(home.join(".codex/config.toml"), "notify = [\"x\"]\n").unwrap();
        assert_eq!(run("codex x", true), "[x]");
        // No real program on PATH nor in the usual install dirs: 127.
        let bare = |cmd: &str| {
            Command::new("/bin/sh")
                .arg("-c")
                .arg(cmd)
                .env(
                    "PATH",
                    format!("{}:/usr/bin:/bin", files.shim_dir.display()),
                )
                .env("HOME", &home)
                .env_remove(civet_proto::ENV_STATUS_FILE)
                .output()
                .unwrap()
        };
        assert_eq!(bare("claude").status.code(), Some(127));
        // Installed only in ~/.local/bin (added by an interactive rc file,
        // so not on the login PATH): found there.
        let local_bin = home.join(".local/bin");
        std::fs::create_dir_all(&local_bin).unwrap();
        std::fs::copy(real.join("claude"), local_bin.join("claude")).unwrap();
        let out = bare("claude a");
        assert!(out.status.success(), "{out:?}");
        assert_eq!(String::from_utf8(out.stdout).unwrap(), "[a]");
    }

    #[test]
    fn shell_setup_per_shell() {
        let dir = tempfile::tempdir().unwrap();
        let files = install(dir.path()).unwrap();
        let env_of = |s: &ShellSetup, k: &str| {
            s.env
                .iter()
                .rev()
                .find(|(kk, _)| kk == k)
                .map(|(_, v)| v.clone())
        };
        let fake = |k: &str| match k {
            "PATH" => Some("/usr/bin:/bin".to_owned()),
            "ZDOTDIR" => Some("/home/u/.config/zsh".to_owned()),
            "LC_TERMINAL" => Some("iTerm2".to_owned()),
            _ => None,
        };
        let z = shell_setup("/bin/zsh", &files, fake);
        let shim = files.shim_dir.display().to_string();
        assert_eq!(env_of(&z, "PATH").unwrap(), format!("{shim}:/usr/bin:/bin"));
        assert_eq!(env_of(&z, "TERM_PROGRAM").as_deref(), Some("civet"));
        assert_eq!(env_of(&z, "LC_TERMINAL").as_deref(), Some("civet"));
        assert_eq!(
            env_of(&z, ENV_USER_ZDOTDIR).as_deref(),
            Some("/home/u/.config/zsh")
        );
        assert_eq!(
            env_of(&z, "ZDOTDIR").unwrap(),
            files.zdotdir.display().to_string()
        );
        let b = shell_setup("/usr/bin/bash", &files, |_| None);
        assert!(
            env_of(&b, "PROMPT_COMMAND")
                .unwrap()
                .contains("CIVET_SHIM_DIR")
        );
        assert!(env_of(&b, "LC_TERMINAL").is_none());
        let f = shell_setup("fish", &files, |_| None);
        assert_eq!(f.interactive_args[0], "-C");
        assert_eq!(ShellKind::of("-zsh"), ShellKind::Zsh);
    }

    /// The bash PROMPT_COMMAND puts the shim dir back in front after an rc
    /// file prepended something else.
    #[test]
    fn bash_prompt_command_reorders_path() {
        if !Path::new("/bin/bash").exists() {
            return;
        }
        let out = Command::new("/bin/bash")
            .arg("-c")
            .arg(format!(
                "PATH=/x:$PATH; {BASH_PROMPT_COMMAND}; printf %s \"$PATH\""
            ))
            .env("CIVET_SHIM_DIR", "/shim")
            .env("PATH", "/shim:/usr/bin:/bin")
            .output()
            .unwrap();
        assert!(String::from_utf8_lossy(&out.stdout).starts_with("/shim:/x:"));
    }

    /// The zsh shim restores the user's ZDOTDIR, sources their .zshenv and
    /// (interactive) keeps the shim first after .zshrc prepended to PATH.
    #[test]
    fn zsh_integration() {
        let zsh = ["/bin/zsh", "/usr/bin/zsh"]
            .into_iter()
            .find(|p| Path::new(p).exists());
        let Some(zsh) = zsh else { return };
        let dir = tempfile::tempdir().unwrap();
        let files = install(&dir.path().join("state")).unwrap();
        let user = dir.path().join("userz");
        std::fs::create_dir_all(&user).unwrap();
        std::fs::write(user.join(".zshenv"), "export FROM_USER_ZSHENV=1\n").unwrap();
        std::fs::write(user.join(".zshrc"), "path=(/rc-first $path)\n").unwrap();
        let out = Command::new(zsh)
            .args(["-i", "-c"])
            .arg("_civet_shim_path; print -r -- \"$FROM_USER_ZSHENV|$ZDOTDIR|$path[1]|$path[2]\"")
            .env("HOME", dir.path())
            .env("ZDOTDIR", &files.zdotdir)
            .env(ENV_USER_ZDOTDIR, &user)
            .env(ENV_SHIM_DIR, &files.shim_dir)
            .env(
                "PATH",
                format!("{}:/usr/bin:/bin", files.shim_dir.display()),
            )
            .stdin(Stdio::null())
            .output()
            .unwrap();
        let s = String::from_utf8_lossy(&out.stdout);
        assert_eq!(
            s.trim_end(),
            format!(
                "1|{}|{}|/rc-first",
                user.display(),
                files.shim_dir.display()
            ),
            "stderr: {}",
            String::from_utf8_lossy(&out.stderr)
        );
    }
