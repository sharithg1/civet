//! Generated agent hook files (`<state_dir>/hooks/`).
//!
//! The session writes, at startup:
//!
//! * `civet-status-hook.sh <status>`: a POSIX sh script that writes `<status>`
//!   (plus the `"message"` field of the hook's JSON stdin, if any) to
//!   `$CIVET_STATUS_FILE` atomically. A no-op outside Civet panes.
//! * `claude-settings.json`: Claude Code settings registering that script for
//!   `UserPromptSubmit` / `PreToolUse` / `PostToolUse` (running),
//!   `Notification` (needs input) and `Stop` (done). Passed to `claude` with
//!   `--settings` (see [`claude_args`]).
//!
//! See `HOOKS.md` in this crate for the manual setup of other agents.

use std::path::{Path, PathBuf};

use serde_json::json;

/// File name of the generated status hook script.
pub(crate) const HOOK_SCRIPT: &str = "civet-status-hook.sh";
/// File name of the generated Claude Code settings.
pub(crate) const CLAUDE_SETTINGS: &str = "claude-settings.json";

const SCRIPT: &str = r#"#!/bin/sh
# Generated by civetd. Writes an agent status to $CIVET_STATUS_FILE.
# Usage: civet-status-hook.sh <running|needs_input|done|idle>
# Reads the hook's JSON event from stdin (if any) and uses its "message"
# field as the status message. Always exits 0 so it never blocks the agent.
status="${1:-running}"
input=""
if [ ! -t 0 ]; then
  input=$(cat 2>/dev/null)
fi
[ -n "$CIVET_STATUS_FILE" ] || exit 0
flat=$(printf '%s' "$input" | tr '\n\r' '  ')
case "$flat" in
  # Claude Code's "waiting for your input" reminder after a finished turn is
  # not a new question: keep the current status (usually done).
  *'"notification_type"'*'"idle_prompt"'*) exit 0 ;;
esac
msg=$(printf '%s' "$flat" | sed -nE 's/.*"message"[[:space:]]*:[[:space:]]*"(([^"\\]|\\.)*)".*/\1/p' | head -n 1)
tmp="$CIVET_STATUS_FILE.tmp.$$"
{
  printf '%s\n' "$status"
  if [ -n "$msg" ]; then printf '%s\n' "$msg"; fi
} > "$tmp" 2>/dev/null && mv -f "$tmp" "$CIVET_STATUS_FILE" 2>/dev/null
rm -f "$tmp" 2>/dev/null
exit 0
"#;

/// Quote for POSIX sh (single quotes).
pub(crate) fn sh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

fn claude_settings(script: &Path) -> serde_json::Value {
    let cmd = |status: &str| {
        json!({
            "type": "command",
            "command": format!("{} {status}", sh_quote(&script.to_string_lossy())),
        })
    };
    json!({
        "hooks": {
            "UserPromptSubmit": [{ "hooks": [cmd("running")] }],
            "PreToolUse": [{ "matcher": "*", "hooks": [cmd("running")] }],
            "PostToolUse": [{ "matcher": "*", "hooks": [cmd("running")] }],
            "Notification": [{ "hooks": [cmd("needs_input")] }],
            "Stop": [{ "hooks": [cmd("done")] }],
        }
    })
}

/// Paths of the generated hook files.
#[derive(Debug, Clone)]
pub(crate) struct HookFiles {
    pub claude_settings: PathBuf,
}

/// Write (or refresh) the hook script and Claude settings under
/// `<state_dir>/hooks/`.
pub(crate) fn install(state_dir: &Path) -> std::io::Result<HookFiles> {
    let dir = state_dir.join("hooks");
    std::fs::create_dir_all(&dir)?;
    let script = dir.join(HOOK_SCRIPT);
    write_atomic(&script, SCRIPT.as_bytes())?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(&script, std::fs::Permissions::from_mode(0o755))?;
    }
    let settings = dir.join(CLAUDE_SETTINGS);
    let body =
        serde_json::to_vec_pretty(&claude_settings(&script)).map_err(std::io::Error::other)?;
    write_atomic(&settings, &body)?;
    Ok(HookFiles {
        claude_settings: settings,
    })
}

/// Write via a temp file + rename so readers never see a partial file.
pub(crate) fn write_atomic(path: &Path, data: &[u8]) -> std::io::Result<()> {
    let tmp = path.with_extension(format!("tmp.{}", std::process::id()));
    std::fs::write(&tmp, data)?;
    std::fs::rename(&tmp, path)
}

/// Basename of a program path (`/usr/bin/claude` → `claude`).
pub(crate) fn basename(program: &str) -> &str {
    program.rsplit('/').next().unwrap_or(program)
}

/// Arguments for an agent launch, with `--settings <claude-settings.json>`
/// appended for Claude Code (agent hint `claude` or program basename
/// `claude`) unless the caller already passes `--settings`.
pub(crate) fn claude_args(
    program: &str,
    args: &[String],
    agent: Option<&str>,
    files: &HookFiles,
) -> Vec<String> {
    let is_claude =
        agent.is_some_and(|a| a.eq_ignore_ascii_case("claude")) || basename(program) == "claude";
    let has_settings = args
        .iter()
        .any(|a| a == "--settings" || a.starts_with("--settings="));
    let mut out = args.to_vec();
    if is_claude && !has_settings {
        out.push("--settings".to_owned());
        out.push(files.claude_settings.to_string_lossy().into_owned());
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn quoting() {
        assert_eq!(sh_quote("a b"), "'a b'");
        assert_eq!(sh_quote("it's"), r"'it'\''s'");
    }

    #[test]
    fn installs_and_injects() {
        let dir = tempfile::tempdir().unwrap();
        let files = install(dir.path()).unwrap();
        let v: serde_json::Value =
            serde_json::from_slice(&std::fs::read(&files.claude_settings).unwrap()).unwrap();
        let stop = v["hooks"]["Stop"][0]["hooks"][0]["command"]
            .as_str()
            .unwrap();
        assert!(stop.ends_with(" done"), "{stop}");
        assert!(dir.path().join("hooks").join(HOOK_SCRIPT).exists());

        let args = claude_args("claude", &[], None, &files);
        assert_eq!(args[0], "--settings");
        let args = claude_args("/x/claude", &["--settings=x".into()], None, &files);
        assert_eq!(args, vec!["--settings=x".to_owned()]);
        let args = claude_args("codex", &["a".into()], None, &files);
        assert_eq!(args, vec!["a".to_owned()]);
        let args = claude_args("npx", &[], Some("claude"), &files);
        assert_eq!(args.len(), 2);
    }

    #[test]
    fn script_writes_status_file() {
        let dir = tempfile::tempdir().unwrap();
        install(dir.path()).unwrap();
        let script = dir.path().join("hooks").join(HOOK_SCRIPT);
        let status = dir.path().join("p.status");
        let run = |arg: &str, stdin: &str| {
            use std::io::Write;
            let mut child = std::process::Command::new("/bin/sh")
                .arg(&script)
                .arg(arg)
                .env(civet_proto::ENV_STATUS_FILE, &status)
                .stdin(std::process::Stdio::piped())
                .spawn()
                .unwrap();
            child
                .stdin
                .take()
                .unwrap()
                .write_all(stdin.as_bytes())
                .unwrap();
            assert!(child.wait().unwrap().success());
            std::fs::read_to_string(&status).unwrap_or_default()
        };
        let got = run(
            "needs_input",
            r#"{"hook_event_name":"Notification","message":"Claude needs your permission to use Bash"}"#,
        );
        assert_eq!(
            civet_proto::parse_status_file(&got),
            Some((
                civet_proto::AgentStatus::NeedsInput,
                Some("Claude needs your permission to use Bash".into())
            ))
        );
        let got = run("done", "{}");
        assert_eq!(
            civet_proto::parse_status_file(&got),
            Some((civet_proto::AgentStatus::Done, None))
        );
        // idle reminder leaves the file alone
        let got = run(
            "needs_input",
            r#"{"message":"Claude is waiting for your input","notification_type":"idle_prompt"}"#,
        );
        assert_eq!(
            civet_proto::parse_status_file(&got),
            Some((civet_proto::AgentStatus::Done, None))
        );
    }
}
